#!/usr/bin/env node
// generate-banner.mjs — reproducibly generates imports/war3mapImported/SiegeCrystal.mdx
//
// Authors a tiny MDL model (a floating 8-face crystal, additive/unshaded so
// lighting and face winding don't matter) textured with ReplaceableId 1
// (player team color) — nothing Blizzard-authored is embedded. The MDL text
// is parsed with war3-model's parseMDL and emitted as binary MDX with
// generateMDX. Re-run after editing:
//
//   node maps/crossroads-siege/assets/generate-banner.mjs
//
// The custom unit 'n000' in objects-units.json uses this model via
// umdl = war3mapImported\SiegeCrystal.mdx.
//
// The model must stay CLEAN under mdx-m3-viewer's sanityTest (0 errors,
// 0 severes) — a malformed custom MDX hard-crashes the game on map load.
// That requires, at minimum (all learned the hard way):
//   - a Bone whose GeosetAnimId actually resolves: either reference a real
//     GeosetAnim or write "GeosetAnimId None" (war3-model defaults an
//     UNSPECIFIED GeosetAnimId to 0, which is invalid without a GeosetAnim
//     chunk -> game crash);
//   - a "Death" sequence in addition to "Stand" (here the GeosetAnim fades
//     alpha out over the Death interval);
//   - an "Origin Ref" attachment point.
// test/fixes.test.js enforces this with sanityTest on the committed binary.

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { parseMDL, generateMDX, parseMDX } = require('war3-model');

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(HERE, '..', 'imports', 'war3mapImported', 'SiegeCrystal.mdx');

// --- crystal geometry: a 4-sided bipyramid (6 vertices, 8 triangles) -------
const verts = [
  [0, 0, 210],   // 0 top apex
  [0, 0, 20],    // 1 bottom apex
  [55, 0, 105],  // 2 +x
  [0, 55, 105],  // 3 +y
  [-55, 0, 105], // 4 -x
  [0, -55, 105], // 5 -y
];
const faces = [
  [0, 2, 3], [0, 3, 4], [0, 4, 5], [0, 5, 2], // upper pyramid
  [1, 3, 2], [1, 4, 3], [1, 5, 4], [1, 2, 5], // lower pyramid
];
// Outward-ish normals: direction from the crystal core (0,0,105).
const normals = verts.map(([x, y, z]) => {
  const dx = x, dy = y, dz = z - 105;
  const len = Math.hypot(dx, dy, dz) || 1;
  return [dx / len, dy / len, dz / len].map((v) => +v.toFixed(4));
});
const tverts = [[0.5, 0.05], [0.5, 0.95], [0.95, 0.5], [0.5, 0.5], [0.05, 0.5], [0.5, 0.5]];

const fmt = (rows) => rows.map((r) => `\t\t{ ${r.join(', ')} },`).join('\n');

const mdl = `// SiegeCrystal — generated by generate-banner.mjs (wc3-map-toolkit)
Version {
\tFormatVersion 800,
}
Model "SiegeCrystal" {
\tBlendTime 150,
\tMinimumExtent { -55, -55, 0 },
\tMaximumExtent { 55, 55, 220 },
\tBoundsRadius 220,
}
Sequences 2 {
\tAnim "Stand" {
\t\tInterval { 0, 1000 },
\t\tMinimumExtent { -55, -55, 0 },
\t\tMaximumExtent { 55, 55, 220 },
\t\tBoundsRadius 220,
\t}
\tAnim "Death" {
\t\tInterval { 1100, 2000 },
\t\tNonLooping,
\t\tMinimumExtent { -55, -55, 0 },
\t\tMaximumExtent { 55, 55, 220 },
\t\tBoundsRadius 220,
\t}
}
Textures 1 {
\tBitmap {
\t\tImage "",
\t\tReplaceableId 1,
\t}
}
Materials 1 {
\tMaterial {
\t\tLayer {
\t\t\tFilterMode Additive,
\t\t\tUnshaded,
\t\t\tUnfogged,
\t\t\tstatic TextureID 0,
\t\t\tstatic Alpha 0.85,
\t\t}
\t}
}
Geoset {
\tVertices ${verts.length} {
${fmt(verts)}
\t}
\tNormals ${normals.length} {
${fmt(normals)}
\t}
\tTVertices ${tverts.length} {
${fmt(tverts)}
\t}
\tVertexGroup {
${verts.map(() => '\t\t0,').join('\n')}
\t}
\tFaces 1 ${faces.length * 3} {
\t\tTriangles {
\t\t\t{ ${faces.flat().join(', ')} },
\t\t}
\t}
\tGroups 1 1 {
\t\tMatrices { 0 },
\t}
\tMinimumExtent { -55, -55, 0 },
\tMaximumExtent { 55, 55, 220 },
\tBoundsRadius 220,
\tAnim {
\t\tMinimumExtent { -55, -55, 0 },
\t\tMaximumExtent { 55, 55, 220 },
\t\tBoundsRadius 220,
\t}
\tAnim {
\t\tMinimumExtent { -55, -55, 0 },
\t\tMaximumExtent { 55, 55, 220 },
\t\tBoundsRadius 220,
\t}
\tMaterialID 0,
\tSelectionGroup 0,
}
GeosetAnim {
\tAlpha 3 {
\t\tLinear,
\t\t0: 1,
\t\t1100: 1,
\t\t2000: 0,
\t}
\tGeosetId 0,
}
Bone "Root" {
\tObjectId 0,
\tGeosetId 0,
\tGeosetAnimId 0,
}
Attachment "Origin Ref" {
\tObjectId 1,
\tAttachmentID 0,
}
PivotPoints 2 {
\t{ 0, 0, 0 },
\t{ 0, 0, 0 },
}
`;

const model = parseMDL(mdl);
const mdx = Buffer.from(generateMDX(model));
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, mdx);

// self-check: the emitted MDX must parse back with the same shape
const re = parseMDX(mdx.buffer.slice(mdx.byteOffset, mdx.byteOffset + mdx.byteLength));
if (re.Geosets.length !== 1 || re.Geosets[0].Vertices.length !== verts.length * 3) {
  throw new Error('MDX self-check failed: geoset did not round-trip');
}
console.log(`wrote ${OUT} (${mdx.length} bytes, ${re.Geosets.length} geoset, ` +
  `${re.Sequences.map((s) => s.Name).join('/')}, textures: ${re.Textures.map((t) => t.Image).join(', ')})`);
